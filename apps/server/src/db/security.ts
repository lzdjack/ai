// Generates the repeatable security SQL from TENANT_TABLES (docs/06 §2.3, §2.8, §2.12).
// Applied after every migration run, so it must be idempotent. `pnpm gen` writes the result to
// src/db/sql/security.sql (committed for review; verify checks it is up to date).
//
// Per tenant table:
//   ENABLE + FORCE ROW LEVEL SECURITY; policy cc_tenant:
//     workspace: workspace_id = app.current_workspace_id
//     project:   … and project_id = ANY(app.visible_project_ids)
//     mixed:     … and (project_id is null or project_id = ANY(app.visible_project_ids))
//   definerAccess: policy cc_definer for cc_migrator, which owns the SECURITY DEFINER functions
//     (claim work, enter a workspace); FORCE would otherwise lock even them out.
//   appendOnly: runtime account loses UPDATE/DELETE/TRUNCATE and a trigger rejects them anyway.
//   audit: trigger cc_audit_probe records (table, row, actor, txid) for the events cross-check.
import { TENANT_TABLES, type TenantTableMeta } from './schema/tenant.ts';
import './schema/index.ts';
import './events.ts';

export const APP_ROLE = 'cc_app';
export const MIGRATOR_ROLE = 'cc_migrator';

const WS = `nullif(current_setting('app.current_workspace_id', true), '')::uuid`;
const VISIBLE = `coalesce(nullif(current_setting('app.visible_project_ids', true), '')::uuid[], '{}')`;

function predicate(t: TenantTableMeta): string {
  const ws = `${t.workspaceColumn} = ${WS}`;
  if (t.scope === 'project') return `${ws} and project_id = any(${VISIBLE})`;
  if (t.scope === 'mixed') return `${ws} and (project_id is null or project_id = any(${VISIBLE}))`;
  return ws;
}

export function securitySql(): string {
  const out: string[] = [
    '-- Generated by apps/server/src/db/security.ts from the table helper registry. Do not edit (pnpm gen).',
    '-- Re-applied after every migration run; must stay idempotent.',
    `grant select, insert, update, delete on all tables in schema public to ${APP_ROLE};`,
    `grant usage, select on all sequences in schema public to ${APP_ROLE};`,
  ];
  const tables = [...TENANT_TABLES].sort((a, b) => a.name.localeCompare(b.name));
  for (const t of tables) {
    const p = predicate(t);
    out.push(
      '',
      `-- ${t.name} (${[t.scope, t.audit && 'audit', t.appendOnly && 'append-only', t.definerAccess && 'definer'].filter(Boolean).join(', ')})`,
      `alter table ${t.name} enable row level security;`,
      `alter table ${t.name} force row level security;`,
      `drop policy if exists cc_tenant on ${t.name};`,
      `create policy cc_tenant on ${t.name} using (${p}) with check (${p});`,
      `drop policy if exists cc_definer on ${t.name};`,
    );
    if (t.definerAccess)
      out.push(
        `create policy cc_definer on ${t.name} to ${MIGRATOR_ROLE} using (true) with check (true);`,
      );
    out.push(`drop trigger if exists cc_append_only on ${t.name};`);
    if (t.appendOnly)
      out.push(
        `revoke update, delete, truncate on ${t.name} from ${APP_ROLE};`,
        `create trigger cc_append_only before update or delete on ${t.name} for each row execute function cc_reject_change();`,
      );
    out.push(`drop trigger if exists cc_audit_probe on ${t.name};`);
    if (t.audit)
      out.push(
        `create trigger cc_audit_probe after insert or update or delete on ${t.name} for each row execute function cc_audit_probe('${t.workspaceColumn}');`,
      );
  }
  out.push(
    '',
    '-- partitions do not inherit the parent RLS: the runtime account goes through the parent only',
    `do $$ declare r record; begin
  for r in select c.relname from pg_inherits i join pg_class c on c.oid = i.inhrelid
           join pg_class p on p.oid = i.inhparent where p.relname = 'events' loop
    execute format('revoke all on %I from ${APP_ROLE}', r.relname);
  end loop;
end $$;`,
    '',
  );
  return out.join('\n');
}
