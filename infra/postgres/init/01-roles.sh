#!/bin/bash
# 首次初始化数据目录时执行：迁移账号与运行账号分离（06 §13.4 第 1 步），运行账号不能绕过 RLS。
set -euo pipefail
psql -v ON_ERROR_STOP=1 --username "$POSTGRES_USER" --dbname "$POSTGRES_DB" <<SQL
CREATE ROLE cc_migrator LOGIN PASSWORD '${CC_MIGRATOR_PASSWORD}';
CREATE ROLE cc_app LOGIN PASSWORD '${CC_APP_PASSWORD}' NOSUPERUSER NOCREATEDB NOCREATEROLE NOBYPASSRLS;
ALTER DATABASE "${POSTGRES_DB}" OWNER TO cc_migrator;
ALTER SCHEMA public OWNER TO cc_migrator;
REVOKE ALL ON SCHEMA public FROM PUBLIC;
GRANT USAGE ON SCHEMA public TO cc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE cc_migrator IN SCHEMA public
  GRANT SELECT, INSERT, UPDATE, DELETE ON TABLES TO cc_app;
ALTER DEFAULT PRIVILEGES FOR ROLE cc_migrator IN SCHEMA public
  GRANT USAGE, SELECT ON SEQUENCES TO cc_app;
CREATE EXTENSION IF NOT EXISTS pg_bigm;
SQL
